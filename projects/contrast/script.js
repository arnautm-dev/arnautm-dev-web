/* ================= LANGUAGE DETECTION ================= */

// Idioma del navegador (ex: "ca-ES", "es-ES", "en-US", "fr-FR")
const browserLocale =
    navigator.languages?.[0] ||
    navigator.language ||
    "en-GB";

/**
 * Cerca el millor idioma disponible a TRANSLATIONS
 * 1. Coincidència exacta (ca-ES)
 * 2. Coincidència per idioma base (ca → ca-ES)
 * 3. Fallback a anglès
 */
function findMatchingLocale(locale) {
    // Exacte
    if (TRANSLATIONS[locale]) {
        return locale;
    }

    // Idioma base (ca, es, en, fr…)
    const baseLang = locale.split("-")[0];

    const match = Object.keys(TRANSLATIONS).find(key =>
        key.startsWith(baseLang + "-")
    );

    return match || "en-GB";
}

const locale = findMatchingLocale(browserLocale);

const t = key =>
    TRANSLATIONS[locale]?.[key] ||
    TRANSLATIONS["en-EN"]?.[key] ||
    key;


/* ================= STATE ================= */

let textColor = "#5cffb3";
let backgroundColor = "#10421e";

/* ================= DOM ================= */

const textInput = document.getElementById("textColorInput");
const bgInput = document.getElementById("backgroundColorInput");
const textPicker = document.getElementById("textColorPicker");
const bgPicker = document.getElementById("backgroundColorPicker");
const textPreview = document.getElementById("textColorPreview");
const bgPreview = document.getElementById("backgroundColorPreview");
const previewBox = document.getElementById("previewBox");
const ratioEl = document.getElementById("contrastRatio");

/* ================= FUNCTIONS ================= */

function hexToRgb(hex) {
    const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
    return result ? {
        r: parseInt(result[1], 16),
        g: parseInt(result[2], 16),
        b: parseInt(result[3], 16)
    } : null;
}

function luminance({ r, g, b }) {
    const a = [r, g, b].map(v => {
        v /= 255;
        return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
    });
    return 0.2126 * a[0] + 0.7152 * a[1] + 0.0722 * a[2];
}

function contrastRatio(c1, c2) {
    const l1 = luminance(hexToRgb(c1));
    const l2 = luminance(hexToRgb(c2));
    return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
}

function badge(passed) {
    return `<span class="badge ${passed ? "pass" : "fail"}">${passed ? t("pass") : t("fail")}</span>`;
}

function update() {
    previewBox.style.color = textColor;
    previewBox.style.backgroundColor = backgroundColor;

    textPreview.style.background = textColor;
    bgPreview.style.background = backgroundColor;

    const ratio = contrastRatio(textColor, backgroundColor);
    ratioEl.textContent = ratio.toFixed(2) + ":1";

    document.getElementById("normalAAResult").innerHTML = badge(ratio >= 4.5);
    document.getElementById("normalAAAResult").innerHTML = badge(ratio >= 7);
    document.getElementById("largeAAResult").innerHTML = badge(ratio >= 3);
    document.getElementById("largeAAAResult").innerHTML = badge(ratio >= 4.5);
}

/* ================= INIT ================= */

document.querySelectorAll("[id]").forEach(el => {
    if (TRANSLATIONS[locale][el.id]) {
        el.textContent = t(el.id);
    }
});

textInput.value = textColor;
bgInput.value = backgroundColor;
textPicker.value = textColor;
bgPicker.value = backgroundColor;

textInput.oninput = e => { textColor = e.target.value; update(); };
bgInput.oninput = e => { backgroundColor = e.target.value; update(); };
textPicker.oninput = e => { textColor = e.target.value; textInput.value = textColor; update(); };
bgPicker.oninput = e => { backgroundColor = e.target.value; bgInput.value = backgroundColor; update(); };

update();
